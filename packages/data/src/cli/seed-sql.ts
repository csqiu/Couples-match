/**
 * Emits SQL that loads the seed (plus the No Match sentinels) into the
 * `programs` table defined in Phase 4.
 *
 *   pnpm --filter @pairwise/data seed:sql > ../../supabase/seed/programs.sql
 */
import { SEED_PROGRAMS, noMatchSentinels } from '../seed.js';
import type { ProgramRecord } from '../types.js';

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null) => (v == null ? 'null' : String(v));
const b = (v: boolean) => (v ? 'true' : 'false');

const cols = [
  'id', 'name', 'institution', 'specialty_code', 'specialty_name', 'match_type', 'match_name', 'nrmp_code',
  'acgme_id', 'city', 'state', 'address', 'geom', 'geocode_confidence', 'geocode_source', 'cbsa_code',
  'cbsa_name', 'is_advanced', 'source', 'verified', 'created_by_couple',
];
const row = (p: ProgramRecord) =>
  [
    q(p.id), q(p.name), q(p.institution), q(p.specialtyCode), q(p.specialtyName), q(p.matchType), q(p.matchName),
    q(p.nrmpCode), q(p.acgmeId), q(p.city), q(p.state), q(p.address),
    p.lat == null ? 'null' : `ST_SetSRID(ST_MakePoint(${p.lon}, ${p.lat}), 4326)::geography`,
    n(p.geocodeConfidence), q(p.geocodeSource), q(p.cbsaCode), q(p.cbsaName), b(p.isAdvanced), q(p.source),
    b(p.verified), q(p.createdByCouple),
  ].join(', ');

const all = [...noMatchSentinels(), ...SEED_PROGRAMS];
console.log('-- Generated by `pnpm --filter @pairwise/data seed:sql`. Do not edit by hand.');
console.log(`insert into programs (${cols.join(', ')}) values`);
console.log(all.map((p) => `  (${row(p)})`).join(',\n'));
console.log('on conflict (id) do nothing;');
