/**
 * Emits the SQL seed files loaded by `supabase db reset` (see supabase/config.toml):
 *
 *   pnpm --filter @pairwise/data seed:sql
 *
 * writes supabase/seed/specialties.sql (the controlled vocabulary) and
 * supabase/seed/programs.sql (No Match sentinels + seed programs).
 */
import { writeFileSync } from 'node:fs';
import { SEED_PROGRAMS, noMatchSentinels } from '../seed';
import { SPECIALTIES } from '../specialties';
import type { ProgramRecord } from '../types';

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null) => (v == null ? 'null' : String(v));
const b = (v: boolean) => (v ? 'true' : 'false');
const header = '-- Generated by `pnpm --filter @pairwise/data seed:sql`. Do not edit by hand.';

export function specialtiesSql(): string {
  const rows = [
    ...SPECIALTIES.map((s) => `  (${q(s.code)}, ${q(s.name)}, ${q(s.matchType)}, ${q(s.matchName)})`),
    `  ('no-match', 'No Match', 'main', 'Any')`,
  ];
  return `${header}
insert into public.specialties (code, name, match_type, match_name) values
${rows.join(',\n')}
on conflict (code) do update set name = excluded.name, match_type = excluded.match_type, match_name = excluded.match_name;
`;
}

const cols = [
  'id', 'name', 'institution', 'specialty_code', 'specialty_name', 'match_type', 'match_name', 'nrmp_code',
  'acgme_id', 'city', 'state', 'address', 'lat', 'lon', 'geocode_confidence', 'geocode_source', 'cbsa_code',
  'cbsa_name', 'is_advanced', 'source', 'verified',
];
const row = (p: ProgramRecord) =>
  [
    q(p.id), q(p.name), q(p.institution), q(p.specialtyCode), q(p.specialtyName), q(p.matchType), q(p.matchName),
    q(p.nrmpCode), q(p.acgmeId), q(p.city), q(p.state), q(p.address), n(p.lat), n(p.lon),
    n(p.geocodeConfidence), q(p.geocodeSource), q(p.cbsaCode), q(p.cbsaName), b(p.isAdvanced), q(p.source),
    b(p.verified),
  ].join(', ');

export function programsSql(): string {
  const all = [...noMatchSentinels(), ...SEED_PROGRAMS];
  return `${header}
insert into public.programs (${cols.join(', ')}) values
${all.map((p) => `  (${row(p)})`).join(',\n')}
on conflict (id) do nothing;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = new URL('../../../../supabase/seed/', import.meta.url);
  writeFileSync(new URL('specialties.sql', dir), specialtiesSql());
  writeFileSync(new URL('programs.sql', dir), programsSql());
  console.log('Wrote supabase/seed/specialties.sql and supabase/seed/programs.sql');
}
